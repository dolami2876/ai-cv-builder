import { NextRequest, NextResponse } from "next/server";































import { auth } from "@clerk/nextjs/server";































import connectDB from "@/lib/db";































import Job from "@/models/Job";































import JobMatch from "@/models/JobMatch";































import Resume from "@/models/Resume";































import { getEmbedding, cosineSimilarity } from "@/lib/embedding";































import { scoreJobMatch } from "@/lib/matching/score-job";































































export const maxDuration = 60;































































const EMPLOYMENT_TYPE_KEYWORDS: Record<string, string[]> = {































  "full-time": ["full time", "full-time", "toan thoi gian", "fulltime"],































  "part-time": ["part time", "part-time", "ban thoi gian", "parttime"],































  internship: ["intern", "internship", "thuc tap"],































  contract: ["contract", "hop dong"],































  freelance: ["freelance", "freelancer", "tu do"],































  temporary: ["temporary", "tam thoi", "thoi vu"],































};































































const WORK_MODE_KEYWORDS: Record<string, string[]> = {































  onsite: ["onsite", "on-site", "tai van phong", "tai cho"],































  remote: ["remote", "tu xa", "lam viec tu xa", "work from home", "wfh"],































  hybrid: ["hybrid", "ket hop", "linh hoat"],































};































































function normalizeText(input: unknown): string {































  return String(input || "")































    .toLowerCase()































    .normalize("NFD")































    .replace(/[\u0300-\u036f]/g, "")































    .trim();































}































































function buildResumeSummary(resume: any): string {































  const parts: string[] = [];































  if (resume.personalInfo?.fullName) parts.push(`Họ tên: ${resume.personalInfo.fullName}`);































  if (resume.summary) parts.push(`Tóm tắt: ${resume.summary}`);































  if (resume.skills?.length) parts.push(`Kỹ năng: ${resume.skills.join(", ")}`);































  if (resume.experience?.length) {































    const exp = resume.experience.map((e: any) => `${e.role} tại ${e.company}: ${e.description || ""}`).join(". ");































    parts.push(`Kinh nghiệm: ${exp}`);































  }































  if (resume.education?.length) {































    const edu = resume.education.map((e: any) => `${e.degree} - ${e.school}`).join(". ");































    parts.push(`Học vấn: ${edu}`);































  }































  if (resume.targetDomain) parts.push(`Mục tiêu ngành: ${resume.targetDomain}`);































  return parts.join("\n");































}































































function matchesEmploymentType(job: any, selectedEmploymentTypes: string[]): boolean {































  if (selectedEmploymentTypes.length === 0) return true;































































  const haystack = normalizeText(































    [job.jobType, job.title, job.descriptionMarkdown, job.descriptionRaw, job.salaryText]































      .filter(Boolean)































      .join(" ")































  );































































  return selectedEmploymentTypes.some((type) => {































    const keywords = EMPLOYMENT_TYPE_KEYWORDS[type] || [type];































    return keywords.some((kw) => haystack.includes(normalizeText(kw)));































  });































}































































function matchesWorkMode(job: any, selectedWorkModes: string[]): boolean {































  if (selectedWorkModes.length === 0) return true;































































  const haystack = normalizeText(































    [job.jobType, job.title, job.location, job.descriptionMarkdown, job.descriptionRaw]































      .filter(Boolean)































      .join(" ")































  );































































  return selectedWorkModes.some((mode) => {































    const keywords = WORK_MODE_KEYWORDS[mode] || [mode];































    return keywords.some((kw) => haystack.includes(normalizeText(kw)));































  });































}































































function matchesLocationScope(job: any, locationScope: string): boolean {































  if (!locationScope) return true;































































  const haystack = normalizeText(































    [job.location, job.title, job.descriptionMarkdown, job.descriptionRaw]































      .filter(Boolean)































      .join(" ")































  );































































  const vnKeywords = [































    "viet nam",































    "vietnam",































    "ho chi minh",































    "hcm",































    "ha noi",































    "danang",































    "da nang",































    "can tho",































    "hue",































  ];































































  const isVietnam = vnKeywords.some((keyword) => haystack.includes(keyword));































































  if (locationScope === "vietnam") return isVietnam;































  if (locationScope === "abroad") return !isVietnam;































































  return true;































}































































function filterJobsByPreferences(































  jobs: any[],































  selectedEmploymentTypes: string[],































  selectedWorkModes: string[],































  locationScope: string































): any[] {































  return jobs.filter(































    (job) =>































      matchesEmploymentType(job, selectedEmploymentTypes) &&































      matchesWorkMode(job, selectedWorkModes) &&































      matchesLocationScope(job, locationScope)































  );































}































































export async function GET(req: NextRequest) {































  try {































    const { userId } = await auth();































    if (!userId) {































      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });































    }































































    await connectDB();































































    const { searchParams } = new URL(req.url);































    const resumeId = searchParams.get("resumeId");































    const forceRefresh = searchParams.get("refresh") === "1";















    const limit = Math.min(Math.max(Number(searchParams.get("limit") || 20), 1), 50);







    const offset = Math.max(Number(searchParams.get("offset") || 0), 0);































































    const selectedEmploymentTypes = (searchParams.get("employmentTypes") || "")































      .split(",")































      .map((s) => normalizeText(s))































      .filter(Boolean);































































    const selectedWorkModes = (searchParams.get("workModes") || "")































      .split(",")































      .map((s) => normalizeText(s))































      .filter(Boolean);































































    const locationScope = normalizeText(searchParams.get("locationScope") || "");































































    let resume: any = null;































    if (resumeId) {































      resume = await Resume.findOne({ _id: resumeId, userId }).lean();































    }































    if (!resume) {































      resume = await Resume.findOne({ userId }).sort({ updatedAt: -1 }).lean();































    }































    if (!resume) {































      return NextResponse.json(































        { error: "Bạn chưa có CV nào. Hãy tạo CV trước để nhận gợi ý việc làm." },































        { status: 400 }































      );































    }































































    const rid = resume._id.toString();































    const summary = buildResumeSummary(resume);































































    // Danh sách đã match trước đó (để refresh có thể tìm thêm job mới, không trùng)































    const existingMatches = await JobMatch.find({ userId, resumeId: rid })































      .select("jobId")































      .lean();































    const existingMatchedJobIds = new Set(































      existingMatches.map((m: any) => String(m.jobId)).filter(Boolean)































    );































































    if (!forceRefresh) {































      const existing = await JobMatch.find({ userId, resumeId: rid })































        .sort({ score: -1, matchedAt: -1 })































        .limit(50)































        .populate("jobId")































        .lean();































































      if (existing.length > 0) {































        const jobs = existing































          .filter((m: any) => m.jobId)































          .map((m: any) => {































            const j = m.jobId && typeof m.jobId === "object" ? m.jobId : {};































            return {































              ...j,































              matchScore: m.score,































              matchExplanation: m.explanation,































              matchedAt: m.matchedAt,































            };































          });































































        const filteredJobs = filterJobsByPreferences(































          jobs,































          selectedEmploymentTypes,































          selectedWorkModes,































          locationScope































        );































































        const pagedJobs = filteredJobs.slice(offset, offset + limit);







        return NextResponse.json({



          jobs: pagedJobs,



          fromCache: true,



          pagination: {



            offset,



            limit,



            total: filteredJobs.length,



            hasMore: offset + pagedJobs.length < filteredJobs.length,



          },



        });































      }































    }































































    const jobsWithEmbedding = await Job.find({ embedding: { $exists: true, $ne: [] } })































      .select("+embedding")































      .sort({ scrapedAt: -1 })































      .limit(300)































      .lean();































































    let candidateJobs = jobsWithEmbedding as any[];































































    if (candidateJobs.length > 0) {































      const resumeEmbedding = await getEmbedding(summary);































      candidateJobs = candidateJobs































        .map((j) => ({































          ...j,































          _similarity: cosineSimilarity(resumeEmbedding, j.embedding || []),































        }))































        .sort((a, b) => (b._similarity || 0) - (a._similarity || 0))































        .slice(0, 120);































    } else {































      candidateJobs = await Job.find({}).sort({ scrapedAt: -1 }).limit(120).lean();































    }































































    const filteredCandidates = filterJobsByPreferences(































      candidateJobs,































      selectedEmploymentTypes,































      selectedWorkModes,































      locationScope































    ).filter((job) => {































      // Khi refresh: chỉ lấy các job chưa từng match để user có thêm job mới































      if (!forceRefresh) return true;































      return !existingMatchedJobIds.has(String(job._id));































    });































































    const results: Array<{ job: any; score: number; explanation: string }> = [];































































    const targetCount = Math.min(filteredCandidates.length, offset + limit);



    for (let i = 0; i < targetCount; i++) {































      const job = filteredCandidates[i];































      const jobId = String(job._id);































      const existingMatch = await JobMatch.findOne({ userId, jobId }).lean();































      if (existingMatch) {































        results.push({































          job,































          score: existingMatch.score,































          explanation: existingMatch.explanation || "",































        });































        continue;































      }































































      try {































        const { score, explanation } = await scoreJobMatch(































          summary,































          job.title,































          job.company,































          job.descriptionMarkdown || "",































          job.skills || []































        );































































        await JobMatch.findOneAndUpdate(































          { userId, jobId },































          {































            userId,































            resumeId: rid,































            jobId: job._id,































            score,































            explanation,































            matchedAt: new Date(),































          },































          { upsert: true, new: true }































        );































































        results.push({ job, score, explanation });































      } catch (err) {































        console.error("Score job error:", job.title, err);































      }































    }































































    results.sort((a, b) => b.score - a.score);































































    const jobs = results.map((r) => {































      const { embedding: _, _similarity: __, ...rest } = r.job;































      return {































        ...rest,































        matchScore: r.score,































        matchExplanation: r.explanation,































      };































    });































































    const pagedJobs = jobs.slice(offset, offset + limit);

    return NextResponse.json({
      jobs: pagedJobs,
      fromCache: false,
      pagination: {
        offset,
        limit,
        total: jobs.length,
        hasMore: offset + pagedJobs.length < jobs.length,
      },
    });































  } catch (error: any) {































    console.error("Jobs recommended error:", error);































    return NextResponse.json(































      { error: error.message || "Internal Server Error" },































      { status: 500 }































    );































  }































}































